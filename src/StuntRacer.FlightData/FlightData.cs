/// <summary>Original values, never regenerated by trigonometric formulae.</summary>
public sealed class FlightTable
{
    public FlightTableMetadata Metadata { get; }
    public ReadOnlyMemory<byte> Bytes { get; }
    internal FlightTable(FlightTableMetadata metadata, byte[] bytes) { Metadata = metadata; Bytes = bytes; }
    public short ReadInt16(int index)
    {
        if (Metadata.Encoding != "i16le" || index < 0 || index >= Metadata.ElementCount)
            throw new FlightDataException("table.index", $"Invalid word access to {Metadata.Name} at index {index}.");
        return BinaryPrimitives.ReadInt16LittleEndian(Bytes.Span.Slice(index * 2, 2));
    }
    public short[] ToInt16Array()
    {
        if (Metadata.Encoding != "i16le") throw new FlightDataException("table.encoding", $"{Metadata.Name} is not an i16le table.");
        var result = new short[Metadata.ElementCount];
        for (int i = 0; i < result.Length; i++) result[i] = ReadInt16(i);
        return result;
    }
}

public sealed class FlightDiskPackage
{
    public int SchemaVersion => 1;
    public string Kind => "fa18-amiga-runtime";
    public FlightSourceIdentity Source { get; }
    public FlightImage FlatImage { get; }
    /// <summary>
    /// Indexed by flat addresses, but every relocation VALUE uses the captured reference-machine
    /// RAM base of its target hunk. This is not a generally dereferenceable flat-pointer image.
    /// Live text/display/variable bytes are NOT snapshots; see Compatibility.Limitations.
    /// </summary>
    public FlightImage ReferenceImage { get; }
    /// <summary>Flat pointers outside the two numeric spans; 340 captured-RAM relocation values inside.</summary>
    public FlightImage ReferenceWindowImage { get; }
    public IReadOnlyList<FlightHunk> Hunks { get; }
    public IReadOnlyList<FlightRelocation> Relocations { get; }
    public IReadOnlyList<FlightSymbol> Symbols { get; }
    public IReadOnlyList<FlightReferenceSegment> ReferenceSegments { get; }
    public IReadOnlyList<FlightDiskFile> DiskFiles { get; }
    public IReadOnlyDictionary<string, FlightTable> Tables { get; }
    public FlightScene Scene { get; }
    public FlightCompatibility Compatibility { get; }
    internal byte[] InputBytes { get; }
    internal string? InputFileName { get; }

    internal FlightDiskPackage(FlightSourceIdentity source, byte[] input, string? inputFileName,
        FlightHunkImage hunkImage, FlightImage referenceImage, IReadOnlyList<FlightReferenceSegment> segments,
        IReadOnlyList<FlightDiskFile> files, IDictionary<string, FlightTable> tables,
        FlightScene scene, FlightCompatibility compatibility)
    {
        Source = source; InputBytes = input; InputFileName = inputFileName;
        FlatImage = hunkImage.FlatImage; ReferenceImage = referenceImage;
        var window = FlatImage.Bytes.ToArray();
        foreach (var range in new[] { new FlightTableRange(0x3249A, 286), new FlightTableRange(0x3AE92, 60288) })
            ReferenceImage.Slice(range.Address, range.ByteCount).CopyTo(window.AsSpan(range.Address - 0x10000));
        ReferenceWindowImage = new FlightImage(window);
        Hunks = hunkImage.Hunks; Relocations = hunkImage.Relocations;
        Symbols = hunkImage.Symbols; ReferenceSegments = segments; DiskFiles = files;
        Tables = new ReadOnlyDictionary<string, FlightTable>(tables);
        Scene = scene; Compatibility = compatibility;
    }
}

