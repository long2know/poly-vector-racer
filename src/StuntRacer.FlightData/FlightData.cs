}

/// <summary>Big-endian image, addressed using the documented flat addresses, never host pointers.</summary>
public sealed class FlightImage
{
    private readonly byte[] bytes;
    public int ImageBase => 0x10000;
    public int Length => bytes.Length;
    public int EndAddress => checked(ImageBase + Length);
    public string Sha256 { get; }
    public ReadOnlyMemory<byte> Bytes => bytes;

    internal FlightImage(byte[] bytes)
    {
        this.bytes = bytes;
        Sha256 = Hashes.Sha256(bytes);
    }

    public bool Contains(int address, int length) =>
        length >= 0 && address >= ImageBase && (long)address + length <= EndAddress;

    public ReadOnlySpan<byte> Slice(int address, int length)
    {
        if (!Contains(address, length))
            throw new FlightDataException("image.range", $"Image read 0x{address:X}+{length} is outside 0x{ImageBase:X}..0x{EndAddress:X}.", address);
        return bytes.AsSpan(address - ImageBase, length);
    }

    public byte ReadByte(int address) => Slice(address, 1)[0];
    public sbyte ReadSByte(int address) => unchecked((sbyte)ReadByte(address));
    public short ReadInt16(int address) => BinaryPrimitives.ReadInt16BigEndian(Slice(address, 2));
    public ushort ReadUInt16(int address) => BinaryPrimitives.ReadUInt16BigEndian(Slice(address, 2));
    public int ReadInt32(int address) => BinaryPrimitives.ReadInt32BigEndian(Slice(address, 4));
    public uint ReadUInt32(int address) => BinaryPrimitives.ReadUInt32BigEndian(Slice(address, 4));
}

